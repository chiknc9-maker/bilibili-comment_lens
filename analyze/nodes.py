"""nodes.py — M1 分析节点：立场地图 / 垃圾解剖 / 最佳论证 / 可疑事实

每个节点是纯函数 (ctx: dict) -> dict，只读 ctx 里它需要的字段、只写自己的
字段——这样后续无论是顺序执行还是迁到 LangGraph StateGraph 都无需改节点。

═══ 产品价值观（写进每个分析节点提示词的公共原则）═══
1. 分析论证，不判定立场：AI 不评价"谁对谁错/哪种立场合理"，只评价论证质量
   （论据是否可靠、推理是否成立、是否回避问题）。左右两派接受同一标准。
2. 报告匿名化：输出永远不出现用户名，只引用评论内容。
3. 教学导向：指出问题要讲清"为什么这种话术有说服力"，而非单纯贬低。
4. 不预设模型自身立场：模型的政治/价值偏好不得影响归类。
"""
from __future__ import annotations

SYSTEM_CORE = """你是一名网络评论分析员，正在分析一个B站争议视频的评论区。
铁律：
- 你的任务是分析"论证质量"和"讨论结构"，绝不评判任何一方的立场对错。
- 不要带入你自己的政治/价值立场，不要表现出对任何一方的倾向。
- 输出中不得出现用户名（uname），引用评论时用 [T序号] 标注即可。
- 涉及历史的讨论只区分"事实断言"与"观点"，不为任何事实断言背书或证伪。
- 语境铁律：中文互联网评论大量使用反讽、玩梗与亚文化黑话（圈子梗、双关、
  抽象话术），字面意思不等于真实意图。遇到用词突兀、语气夸张、逻辑反常、
  或读起来不像认真发言的评论，先怀疑是在玩梗或反讽，按上下文解读，不要
  按字面意思归类、解剖或引用。对拿不准是否为梗的表达，如实标注
  "疑似圈子梗/反讽，含义未确认"，不要自信地给出字面解读。
- 所有输出必须是合法的 JSON 对象。"""


def node_stance_map(llm, corpus_text: str) -> dict:
    """N1 立场地图：聚类阵营、定位核心分歧、检测"各说各话"错位。"""
    system = SYSTEM_CORE + """
现在执行"争论地图"分析，输出 JSON：
{
  "stances": [
    {"name": "阵营简称", "summary": "该阵营核心主张（30字内）",
     "thread_ids": [带T的序号], "size": 阵营里主评论数量}
  ],
  "core_disputes": [
    {"question": "双方实际在争的命题（写清主语与谓语）",
     "sides": ["甲方的论证要点", "乙方的论证要点"],
     "dimension": "事实层|价值层|可行层|定义层"}  // 冲突主要发生在哪一层
  ],
  "mismatches": [
    {"description": "哪些楼在'各说各话'（例如定义不同、举的例子不同、讨论层面错位）",
     "thread_ids": [相关序号], "note": "为什么算错位"}
  ]
}
要求：
- stances 给 2~6 个，把"站队评论"与"非立场评论（玩梗/灌水/纯提问）"分开，
  后者归入 name="其他/非立场"（若存在）。
- core_disputes 给 1~4 个真正的分歧命题；若评论区主要在争事实（某个历史事件
  的经过/数字），dimension 标"事实层"并如实写 sides。
- mismatches 是可选亮点：找不到就不要编造，给空数组。"""
    result = llm.chat_json(system, f"评论区内容如下（[T序号]开头为一条主评论及其回复）：\n\n{corpus_text}")
    for s in result.get("stances", []):
        s["thread_ids"] = [i for i in s.get("thread_ids", []) if str(i).startswith("T")]
    return result


def node_pick_junk(llm, corpus_text: str, n: int = 5) -> dict:
    """N2a 候选挑选：选出'高互动但论证质量低/话术主导'的评论作为解剖对象。

    注意：挑选标准是论证质量，与立场无关——任何立场的烂论证都可能被选中。
    主楼与其回复是分别评估的：主楼烂选主楼，回复烂选回复（标 T序号_回复N）。
    """
    system = SYSTEM_CORE + """
从评论中挑选 """ + str(n) + """ 处"高互动/高传播但论证质量低"的评论作为教学解剖
对象。注意是"处"：一处可以是主楼，也可以是其中一条回复（如 T3_回复2）。

值得抓的典型话术（优先挑这类）：
- 把严肃历史/争议事件轻佻化、梗化（"闹着玩似的""当笑话讲"）
- 用传闻当论据："我听说/身边人都说/众所周知/有人说…"但给不出源
- 拿极端个案代表整体；拿比喻、类比直接替代论证
- 看似中立、实则偷塞断言（"其实大家都清楚…"）
- 数字/历史细节信口开河、混淆时间线
- 用情绪、玩梗、人身归因替代论证

不要挑：纯提问（真在问问题）、纯脏话、有实质论据的评论、无实质文字内容的
图文评论（如只发"我的政治考试："配图、只刷歌词/口号）、纯玩梗附和、
单纯纠正他人错误且纠正正确的评论（无论语气多嘲讽，正确的纠错不是烂论证——
只有当纠错本身错误、或借纠错攻击人时才值得解剖）。
输出 JSON：
{
  "picks": [
    {"thread_id": "T序号",  // 回复用 T序号_回复N
     "reason": "为什么值得解剖（30字内，说明话术类型）"}
  ]
}"""
    return llm.chat_json(system, f"评论区内容：\n\n{corpus_text}")


def node_autopsy(llm, threads_text: list[tuple[str, str]]) -> dict:
    """N2b 逐条解剖。每个输入是"争论串"（主楼+若干回复）。

    边界铁律（决定报告是否公正）：
    1. 合理提问、讽刺、情绪表达本身【不是】论证缺陷——只有"用它们替代论证、
       逃避回应"才算。不要把评论者的表达风格病理化。
    2. 讽刺性评论中作为背景出现的历史细节，只有当它被当作支撑论点的断言
       时才需要核出处；纯粹的文学性反讽不解剖。
    3. 解剖的是"论证"，不是"人"。强度、粗俗度不构成缺陷。
    约束：每个争论串最多 1 条主楼解剖 + 2 条回复解剖（纯玩梗附和不解剖）。
    """
    item_prompt = "\n\n".join(f"{tid}:\n{text}" for tid, text in threads_text)
    system = SYSTEM_CORE + """
对给出的每个"争论串"（含主楼与回复）做"论证解剖"。注意控制数量：
- 每个争论串必须解剖其主楼，输出 1 条
- 回复只在"论证问题典型、有教学价值"时才选出来解剖，每个串最多选 2 条回复
输出 JSON：
{
  "items": [
    {
      "thread_id": "T序号（回复用 T序号_回复N 标注）",
      "evidence_problems": ["论据层问题：如数据存疑/以偏概全/传闻当论据/混淆时间线…（没有则空数组）"],
      "reasoning_problems": ["推理层问题：如滑坡/循环论证/非黑即白/错误因果…"],
      "emotion_problems": ["情绪层问题：只有在情绪【替代了论证】时才算：如人身攻击回避论点、道德绑架（情绪强烈本身不算）"],
      "rhetoric_problems": ["修辞层问题：如偷换概念/扣帽子/阴阳话术替代论证（纯文学性反讽不算）"],
      "why_convincing": "为什么这种说法对很多人有说服力（针对什么心理/迎合了什么情绪，60字内）",
      "kernel": "值得认真回应的观点内核（即使论证烂，其背后可能有关切或合理疑问；确实没有则写'无'）",
      "reply_demo": "一句示范性回应。要求像真人高质量回复：具体、有信息量，可以给事实/数据/反问/反例，立场可以鲜明但讲理；禁止万能空话如'值得关注''需全面考量''理解您的感受，但…''有一定道理'。"
    }
  ]
}
要求：每层没有发现就别写（空数组），绝不凑数；kernel 要诚实；
items 总数不得超过输入争论串数量的 3 倍。"""
    return llm.chat_json(system, f"待解剖评论（[T序号]为一个争论串，含主楼与回复）：\n\n{item_prompt}")


def node_best_args(llm, corpus_text: str, exclude_ids: list[str] | None = None) -> dict:
    """N3 最佳论证：为每个立场阵营各挑 1~2 条论证质量高的范本。

    exclude_ids：已被"垃圾解剖"选中的评论（主楼级），范本必须避开，
    避免同一条评论既被解剖又被表扬（自相矛盾）。
    """
    ex = exclude_ids or []
    system = SYSTEM_CORE + """
从评论中挑出论证质量最高的几条作为"值得学习的范本"（每个主要立场阵营
尽量覆盖，不偏袒任何一方）。标准：有事实依据或推理清晰、认真回应了对方、
不搞人身攻击。

重要：以下评论（主楼级）已被另选为"解剖对象"，范本**必须避开**，
不要挑它们（其楼内未被解剖的回复仍可入选）：
""" + ("、".join(ex) if ex else "（本轮无解剖对象）") + """
输出 JSON：
{
  "items": [
    {"thread_id": "T序号", "stance": "它代表的阵营",
     "why_good": "为什么这条论证是好的（50字内，说明好在哪里：论据/推理/态度）"}
  ]
}"""
    return llm.chat_json(system, f"评论区内容：\n\n{corpus_text}")


def node_insights(llm, corpus_text: str, autopsy_items: list[dict]) -> dict:
    """N5 洞察：低质评论的社会学观察 + 评论区没解决的问题。

    这是产品"垃圾之中有思辨价值"的收束节点：论证质量低 ≠ 信息价值低。
    但铁律：每条观察必须能从评论区内容中找到证据，禁止空谈。
    """
    autopsy_summary = "\n".join(
        f"- {it.get('thread_id')}: 问题={it.get('evidence_problems') or it.get('reasoning_problems') or it.get('emotion_problems') or it.get('rhetoric_problems')}"
        for it in autopsy_items)
    system = SYSTEM_CORE + """
现在做一个"更高一层"的观察（这是你的任务中最具洞察力的部分）：
把评论区中大量出现、但论证质量不高的表达（情绪、偏见、刻板印象、玩梗、话术）
当作**社会认知的窗口**来解读——它们各自在反映什么？注意：
- 观察必须有评论区证据支撑（引用评论原文片段），没有证据宁可不写
- 对现象的解读要克制：说"这可能反映了…"而不下断语
- 你可以注意到情绪性评论指向的【未被承认的关切】（即使表达很烂）
输出 JSON：
{
  "readings": [
    {"phenomenon": "现象（如：历史悲剧被梗化/站队式史观/用'体制论'回避具体分析）",
     "evidence": "评论原文片段（1~2条，从给出的语料中引用）",
     "reflection": "它反映了什么：背后的心理机制/认知模式/社会语境（60~100字）"}
  ],
  "open_questions": [
    {"question": "评论区认真讨论了但最终没有解决的问题",
     "why_hard": "为什么难解决（信息不足/价值冲突/立场预设/问题本身无解…）"}
  ]
}
readings 给 2~4 条，open_questions 给 2~3 条。"""
    return llm.chat_json(
        system,
        f"已解剖的评论问题清单：\n{autopsy_summary}\n\n评论区全文：\n\n{corpus_text}",
        max_tokens=3072)


def node_suspect_facts(llm, corpus_text: str) -> dict:
    """N4 可疑事实清单：评论区高频出现、需要核实的事实性断言。

    硬约束：最多 10 条、按"若为假对讨论误导程度"排序取前 10、不得重复列出。
    """
    system = SYSTEM_CORE + """
提取评论区中出现的"事实性断言"（数字、统计、历史事件经过、作品内容、
人物背景、引语等可被验证对错的内容）。这些断言是争论的火药桶。

筛选铁律：
- **重要性**：只列"一旦为假会显著误导讨论"的公共断言。排除：纯玩笑/反讽/
  明显不真（如"XX是谷爱凌"）、私人八卦、无法验证的个人主观、纯比喻
  （如"安卓说唱"）。
- 同一断言多人重复时必须合并为一条，绝不重复列出。
- 不为任何断言下"对/错"结论，只标"待核实"。
- **最多输出 10 条**，按重要性从高到低排列。
输出 JSON：
{
  "facts": [
    {"claim": "被断言的事实",
     "appears_in": ["T序号", ...],
     "why_suspicious": "为什么值得核实（50字内）"}
  ]
}
没有符合条件的事实断言时 facts 给空数组。"""
    return llm.chat_json(system, f"评论区内容：\n\n{corpus_text}", max_tokens=2048)
